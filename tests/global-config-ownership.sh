# [T0-3] 只守住 guard tokenizer 的已知 regression seam：`read -r -a <array>` 不得改回
# here-doc／here-string。這不是所有 hook、也不是所有 shell redirect 的 parser；收窄到實際失效
# 形狀；只認歷史四個 target arrays，避免合法算術左移、quoted literal 與無關 hook false-red。
has_guard_tokenizer_redirect() { # $1=待掃檔案；rc 0=乾淨 1=有命中（已印到 stderr）2=掃描失敗
  local src hits rc=0 join_rc=0 hits_rc=0
  # `--` 不可省：路徑以 `-` 開頭時 grep 會當成 option，印自己的說明而非檔案內容，命中為空
  # → 靜態斷言靜默通過。兩個 grep 必須拆開跑：pipefail 回的是最右的非零狀態，第一個的
  # rc=2（讀不到）會被第二個的 rc=1（無命中）遮掉，於是「讀不到」被當成「乾淨」。
  src="$(grep -vE '^[[:space:]]*#' -- "$1")" || rc=$?
  [ "$rc" -lt 2 ] || return 2
  # `\` + newline 在 tokenize 前被移除；接續失敗必須回 rc=2，不能因呼叫端用 `||` 而讓
  # Bash 抑制函式內 errexit，最後拿空字串當作乾淨。
  src="$(printf '%s\n' "$src" | sed -e :a -e '/\\$/N; s/\\\n//; ta')" || join_rc=$?
  [ "$join_rc" -eq 0 ] || return 2
  hits="$(printf '%s\n' "$src" | grep -E \
    '^[[:space:]]*(IFS=[^[:space:]]+[[:space:]]+)?read[[:space:]]+[^#]*[[:space:]](toks|win_toks|cmd_segments|win_segments)[[:space:]]*<<-?[[:space:]]*[^[:space:]]')" || hits_rc=$?
  [ "$hits_rc" -lt 2 ] || return 2
  [ -z "$hits" ] || { printf '%s\n' "$hits" >&2; return 1; }
  return 0
}

# 偵測器自身的鑑別力。斷言本體在守衛乾淨時恆綠，所以先證明它會紅——否則哪天 pattern 或
# 註解剝除被「簡化」，這條斷言會安靜地失去作用而全套仍然全綠。
#
# 下列 fixtures 分別釘住偵測器部件與歷史 seam，缺一條就有一種簡化能無聲通過：
#   clean      → 不得誤報
#   dirty      → `<<=EOF`（delimiter 為 `=EOF` 的合法 here-doc）。pattern 若為了避開算術
#                左移 `$((a <<= 2))` 的誤報而排除 `=`，這條會紅。
#   inline     → here-string 與行尾註解同一行。註解剝除若從 `^[[:space:]]*#` 簡化成
#                `grep -v '#'`，整行被丟掉、命中消失，這條會紅。
#   continued  → `<<` 被 `\` 換行拆開。少了上面那道 sed，這條會紅。
#   safe-syntax → 合法算術左移、quoted literal 與 inline comment 不得被當成 redirect。
hd_probe="$guard_probe_dir/hd"
mkdir -p "$hd_probe"
printf '#!/usr/bin/env bash\ntoks=($seg)\n' > "$hd_probe/clean.sh"
printf '#!/usr/bin/env bash\nread -r -a toks <<=EOF\n$seg\n=EOF\n' > "$hd_probe/dirty.sh"
printf '#!/usr/bin/env bash\nread -r -a toks <<<"$seg"  # 切詞\n' > "$hd_probe/inline.sh"
# 拆成三段而非兩段：`... <<\` 那一行自己就含 `<<`，不接續也會被抓到，當 fixture 沒有
# 鑑別力（實測過）。每行單獨只有一個 `<`，接續後才是 `<<<`，才真的在驗那道 sed。
printf '#!/usr/bin/env bash\nread -r -a toks <\\\n<\\\n<"$seg"\n' > "$hd_probe/continued.sh"
printf '#!/usr/bin/env bash\nread -ra toks <<< "$seg"\n' > "$hd_probe/combined-option.sh"
printf '#!/usr/bin/env bash\nread -r -a win_toks<<< "$win_seg"\n' > "$hd_probe/compact-redirect.sh"
printf '#!/usr/bin/env bash\nIFS="$SEP" read -r -a cmd_segments <<< "$CMD_SEGMENTS"\n' \
  > "$hd_probe/prefixed-cmd.sh"
printf '#!/usr/bin/env bash\nIFS="$SEP" read -r -a win_segments <<< "$WIN_SEGMENTS"\n' \
  > "$hd_probe/prefixed-win.sh"
printf '#!/usr/bin/env bash\nx=$((x << 1))\necho "literal << token"\n: # <<< note\nread -ra backup_toks <<< "$seg"\n' \
  > "$hd_probe/safe-syntax.sh"

